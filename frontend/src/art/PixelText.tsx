function path(text: string, dx: number, dy: number) {
  let d = "";
  for (let i = 0; i < text.length; i++) {
    const g = (FONT[text[i]] ?? FONT[" "]).split(",");
    for (let y = 0; y < 7; y++) for (let x = 0; x < 5; x++) {
      if (g[y][x] === "1") d += `M${i * 6 + x + dx} ${y + dy}h1v1h-1z`;
    }
  }
  return d;
}

interface Props {
  text: string;
  color?: string;
  shadow?: string;
  height?: number;
  className?: string;
}

/** Decorative pixel text. Callers provide the readable text separately (e.g. a visually hidden heading). */
export function PixelText({ text, color = "#ff2e97", shadow = "#6b1342", height = 28, className }: Props) {
  const t = text.toUpperCase();
  const w = t.length * 6;
  return (
    <svg className={className} viewBox={`0 0 ${w} 8`} height={height} width={(height * w) / 8} shapeRendering="crispEdges"
      aria-hidden="true" focusable="false" style={{ maxWidth: "100%" }}>
      <path fill={shadow} d={path(t, 1, 1)} />
      <path fill={color} d={path(t, 0, 0)} />
    </svg>
  );
}
